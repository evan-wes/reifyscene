#!/usr/bin/env bash
set -euo pipefail

# Snapshot the pip layer of the project conda environments into lockfiles.
#
# A lockfile freezes the ENTIRE resolved pip tree (every transitive dep at an
# exact version), unlike the per-package pins in the setup scripts which only
# fix the top-level things they name. The setup scripts install from these
# locks by default (pass --unlocked to re-resolve), making env rebuilds
# replay the known-good tree instead of resolving whatever is newest.
#
# What is EXCLUDED from each lock (owned by the setup scripts instead):
# - editable installs (-e ...): room4d itself and the third_party checkouts
#   (vggt, co-tracker, hloc, VGGT-Long, ...) are pinned by commit in the
#   setup scripts and installed editable from the local tree.
# - gsplat: built from source for sm_120 at a pinned commit by
#   setup_reference_tool.sh; a pip-resolved gsplat would NOT be that build.
# - the conda layer (cuda-toolkit, compilers): pinned via conda channels in
#   the setup scripts; pip freeze cannot see it.
#
# Locks are platform- and Python-version-specific (linux x86_64; see each
# header). Regenerate after any deliberate dependency upgrade:
#   scripts/gen_env_locks.sh

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LOCK_DIR="${ROOT_DIR}/scripts/locks"
mkdir -p "${LOCK_DIR}"

# env_name -> lock filename
ENVS=(
  "room4d:room4d.lock"
  "room4d_som_ref:room4d_som_ref.lock"
)

find_conda() {
  if [[ -n "${CONDA_EXE:-}" && -x "${CONDA_EXE}" ]]; then
    echo "${CONDA_EXE}"
  elif command -v conda >/dev/null 2>&1; then
    command -v conda
  elif [[ -x "${HOME}/miniconda3/condabin/conda" ]]; then
    echo "${HOME}/miniconda3/condabin/conda"
  else
    echo "conda executable not found (checked CONDA_EXE, PATH, $HOME/miniconda3)." >&2
    exit 1
  fi
}

CONDA_BIN="$(find_conda)"

for entry in "${ENVS[@]}"; do
  env_name="${entry%%:*}"
  lock_name="${entry##*:}"
  lock_path="${LOCK_DIR}/${lock_name}"

  if ! "${CONDA_BIN}" env list | awk '{print $1}' | grep -qx "${env_name}"; then
    echo "Skipping ${env_name}: conda env not found on this machine." >&2
    continue
  fi

  echo "Locking ${env_name} -> ${lock_path}"
  py_version="$("${CONDA_BIN}" run -n "${env_name}" python -c 'import sys; print(".".join(map(str, sys.version_info[:3])))')"
  torch_line="$("${CONDA_BIN}" run -n "${env_name}" python -c 'import torch; print(f"torch {torch.__version__} (cuda {torch.version.cuda})")' 2>/dev/null || echo "torch not installed")"

  {
    echo "# Lockfile for conda env '${env_name}' (pip layer only)."
    echo "# Generated by scripts/gen_env_locks.sh on $(date -u +%Y-%m-%d) — do not edit by hand."
    echo "# Platform: $(uname -s)/$(uname -m) | Python ${py_version} | ${torch_line}"
    echo "# Excludes editable installs and gsplat (owned by the setup scripts)."
    echo "# Install: handled by the setup scripts by default; --unlocked re-resolves."
    echo "# RAPIDS wheels need: --extra-index-url https://pypi.nvidia.com"
    echo "# torch +cuXXX builds need their pytorch index ONLY on a fresh env where"
    echo "# torch is not yet installed (the setup scripts install torch first)."
    "${CONDA_BIN}" run -n "${env_name}" python -m pip freeze --exclude-editable \
      | grep -vE '^gsplat=='
  } > "${lock_path}"

  echo "  $(grep -c '==' "${lock_path}") pinned packages."
done

echo "Done. Commit the updated locks in scripts/locks/."
