#!/usr/bin/env bash
set -euo pipefail

# Snapshot the pip layer of the project conda environments into lockfiles.
#
# A lockfile freezes the ENTIRE resolved pip tree (every transitive dep at an
# exact version), unlike the per-package pins in the setup scripts which only
# fix the top-level things they name. The setup scripts install from these
# locks by default (pass --unlocked to re-resolve), making env rebuilds
# replay the known-good tree instead of resolving whatever is newest.
#
# What is EXCLUDED from each lock (owned by the setup scripts instead):
# - editable installs (-e ...): reifyscene itself and the third_party checkouts
#   (vggt, co-tracker, hloc, VGGT-Long, ...) are pinned by commit in the
#   setup scripts and installed editable from the local tree.
# - gsplat: built from source for sm_120 at a pinned commit by
#   setup_reference_tool.sh; a pip-resolved gsplat would NOT be that build.
# - detectron2: installed from a pinned tag with --no-build-isolation by
#   setup_reifyscene.sh. Freezing it emits an unportable direct-URL line
#   (or, if built from a temp clone, a file:///tmp/... path that is already
#   dead), and reinstalling from the lock would rebuild it WITH build
#   isolation — not the build the setup script produced.
# - the conda layer (cuda-toolkit, compilers): pinned via conda channels in
#   the setup scripts; pip freeze cannot see it.
#
# Locks are platform- and Python-version-specific (linux x86_64; see each
# header). Regenerate after any deliberate dependency upgrade:
#   scripts/gen_env_locks.sh

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LOCK_DIR="${ROOT_DIR}/scripts/locks"
mkdir -p "${LOCK_DIR}"

# env_name -> lock filename
ENVS=(
  "reifyscene:reifyscene.lock"
  "reifyscene_som_ref:reifyscene_som_ref.lock"
)

find_conda() {
  if [[ -n "${CONDA_EXE:-}" && -x "${CONDA_EXE}" ]]; then
    echo "${CONDA_EXE}"
  elif command -v conda >/dev/null 2>&1; then
    command -v conda
  elif [[ -x "${HOME}/miniconda3/condabin/conda" ]]; then
    echo "${HOME}/miniconda3/condabin/conda"
  else
    echo "conda executable not found (checked CONDA_EXE, PATH, $HOME/miniconda3)." >&2
    exit 1
  fi
}

CONDA_BIN="$(find_conda)"

for entry in "${ENVS[@]}"; do
  env_name="${entry%%:*}"
  lock_name="${entry##*:}"
  lock_path="${LOCK_DIR}/${lock_name}"

  _envs="$("${CONDA_BIN}" env list | awk '{print $1}' || true)"
  if ! grep -qx "${env_name}" <<<"${_envs}"; then
    echo "Skipping ${env_name}: conda env not found on this machine." >&2
    continue
  fi

  echo "Locking ${env_name} -> ${lock_path}"
  py_version="$("${CONDA_BIN}" run -n "${env_name}" python -c 'import sys; print(".".join(map(str, sys.version_info[:3])))')"
  torch_line="$("${CONDA_BIN}" run -n "${env_name}" python -c 'import torch; print(f"torch {torch.__version__} (cuda {torch.version.cuda})")' 2>/dev/null || echo "torch not installed")"

  # Write to a temp file and mv into place: a mid-write failure (pip freeze
  # dying under set -o pipefail) must not leave a truncated header-only lock
  # that the setup scripts would then silently "install" from.
  tmp_lock="$(mktemp "${lock_path}.XXXXXX")"
  {
    echo "# Lockfile for conda env '${env_name}' (pip layer only)."
    echo "# Generated by scripts/gen_env_locks.sh on $(date -u +%Y-%m-%d) — do not edit by hand."
    echo "# Platform: $(uname -s)/$(uname -m) | Python ${py_version} | ${torch_line}"
    echo "# Excludes editable installs, gsplat and detectron2 (owned by the setup scripts)."
    echo "# Install: handled by the setup scripts by default; --unlocked re-resolves."
    echo "# Index notes: RAPIDS wheels need --extra-index-url https://pypi.nvidia.com;"
    echo "# torch +cuXXX builds need the matching pytorch index when the lock itself"
    echo "# installs torch (setup_reifyscene.sh passes both; setup_reference_tool.sh"
    echo "# installs torch from its pinned index before the lock runs)."
    # pip freeze emits VCS installs as 'name @ git+...' (not 'name=='), so the
    # gsplat exclusion must match BOTH forms — a leaked 'gsplat @ git+...@SHA'
    # line would make pip rebuild gsplat at that SHA with build isolation ON,
    # bypassing the setup script's pinned, arch-targeted source build.
    "${CONDA_BIN}" run -n "${env_name}" python -m pip freeze --exclude-editable \
      | grep -vE '^(gsplat|detectron2)(==| @ )'
  } > "${tmp_lock}"
  mv "${tmp_lock}" "${lock_path}"

  if grep -qE '^(gsplat|detectron2)' "${lock_path}"; then
    echo "ERROR: gsplat/detectron2 leaked into ${lock_path} despite the exclusion." >&2
    exit 1
  fi

  # A lock is only worth committing if it can actually be installed. `pip freeze`
  # faithfully records whatever is in the env INCLUDING an internally inconsistent
  # state, and it happily emits unportable direct-URL lines for anything installed
  # from a local path. Both have shipped here: a lock pinning mypy==2.3.1 next to
  # pathspec==0.12.1 (mypy needs pathspec>=1) that pip could not resolve at all,
  # and a `detectron2 @ file:///tmp/...` line pointing at an already-deleted build
  # directory. Neither is visible until the next fresh install fails. Resolve the
  # lock here and refuse to write one that cannot be installed.
  if grep -qE '@ file://' "${lock_path}"; then
    echo "ERROR: ${lock_path} contains a local file:// path — not portable." >&2
    grep -nE '@ file://' "${lock_path}" >&2
    exit 1
  fi
  echo "  verifying the lock resolves..."
  if ! resolve_out="$("${CONDA_BIN}" run -n "${env_name}" python -m pip install \
      --dry-run --quiet --report /dev/null -r "${lock_path}" 2>&1)"; then
    echo "ERROR: ${lock_path} is not installable — refusing to write it." >&2
    echo "${resolve_out}" | tail -n 15 >&2
    exit 1
  fi
  echo "  $(grep -c '==' "${lock_path}") pinned packages."
done

echo "Done. Commit the updated locks in scripts/locks/."
